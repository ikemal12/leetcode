class Solution:
    def numIslands(self, grid: List[List[str]]) -> int:
        if not grid: return 0
        ROWS, COLS = len(grid), len(grid[0])
        islands = 0
        visit = set()

        def bfs(r, c):
            q = collections.deque()
            visit.add((r, c))
            q.append((r, c))

            while q:
                row, col = q.popleft()
                dirs = [[1, 0], [-1, 0], [0, 1], [0, -1]]
                for dx, dy in dirs:
                    dr, dc = row + dx, col + dy
                    if dr in range(ROWS) and dc in range(COLS) and grid[dr][dc] == "1" and (dr, dc) not in visit:
                        q.append((dr, dc))
                        visit.add((dr, dc))
                    

        for r in range(ROWS):
            for c in range(COLS):
                if grid[r][c] == "1" and (r, c) not in visit:
                    bfs(r, c)
                    islands += 1
        return islands


        














